const dictionaries:Record<Language,Record<Keys,string>>={en,ru,sr};
function detectLanguage():Language {
  const stored=localStorage.getItem('mmr_lang');
  if(stored==='en'||stored==='ru'||stored==='sr')return stored;
  const locales=navigator.languages?.length?navigator.languages:[navigator.language];
  for(const locale of locales){const primary=locale.toLowerCase().split('-')[0];if(primary==='en'||primary==='ru'||primary==='sr')return primary;}
  return 'en';
}
const Ctx=createContext<{language:Language;setLanguage:(v:Language)=>void;t:(key:Keys)=>string}>({
  language:'en',setLanguage:()=>undefined,t:(key)=>en[key],
});
export function LanguageProvider({children}:{children:ReactNode}) {
  const [language,set]=useState<Language>(detectLanguage);
  const context=useMemo(()=>({language,setLanguage:(v:Language)=>{localStorage.setItem('mmr_lang',v);set(v);},t:(key:Keys)=>dictionaries[language][key]}),[language]);
  return <Ctx.Provider value={context}>{children}</Ctx.Provider>;
}
export const useI18n=()=>useContext(Ctx);
export function LanguageSwitch(){
  const {language,setLanguage}=useI18n();
  return <label className="inline-flex items-center gap-2 text-xs text-muted-foreground">
    <span className="sr-only">Language / Язык / Jezik</span>
    <select aria-label="Language" value={language} onChange={(e)=>setLanguage(e.target.value as Language)} className="rounded-md border border-border bg-card px-2 py-2 text-sm">
      <option value="en">EN</option><option value="ru">RU</option><option value="sr">SR</option>
    </select>
  </label>;
}
